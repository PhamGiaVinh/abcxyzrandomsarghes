-- Pending200k is source evidence, not another payable or a wage cost.
BEGIN;
DO $test$
DECLARE
 owner_id constant uuid:='16770000-0000-4000-8000-000000000001';
 accountant constant uuid:='16770000-0000-4000-8000-000000000002';
 employee constant uuid:='16770000-0000-4000-8000-000000000004';
 foreign_admin constant uuid:='16770000-0000-4000-8000-000000000099';
 club constant uuid:='16770000-0000-4000-8000-000000000011';
 v_staff constant uuid:='16770000-0000-4000-8000-000000000021';
 result jsonb; before_salary jsonb; after_salary jsonb; before_source jsonb;
 before_finance jsonb; packet jsonb; request_id uuid; child_id uuid; denied boolean:=false;
BEGIN
 ASSERT current_database()='vinpoker_ops_l02';
 INSERT INTO auth.users(id)VALUES(owner_id),(accountant),(employee),(foreign_admin);
 INSERT INTO public.profiles(user_id,display_name)VALUES(owner_id,'L02 adjustment owner TEST'),(accountant,'L02 adjustment accountant TEST'),(employee,'L02 adjustment employee TEST'),(foreign_admin,'L02 foreign admin TEST');
 INSERT INTO public.clubs(id,owner_id,name,region,status)VALUES(club,owner_id,'L02 supplement TEST','TEST','approved'),(foreign_admin,foreign_admin,'Other adjustment club TEST','TEST','approved');
 INSERT INTO public.user_roles(user_id,role)VALUES(foreign_admin,'club_admin');
 INSERT INTO public.club_accountants(club_id,user_id,granted_by)VALUES(club,accountant,owner_id);
 INSERT INTO public.staff(id,club_id,user_id,full_name,department,employment_type,monthly_salary_vnd,manual_bhxh_vnd,manual_tax_vnd,status)
 VALUES(v_staff,club,employee,'L02 supplement FT','service','full_time',5200000,0,0,'active');
 INSERT INTO public.staff_attendance(staff_id,shift_date,status,check_in_time,check_out_time)
 SELECT v_staff,date'2026-11-01'+d,'checked_out',(date'2026-11-01'+d+time'09:00')AT TIME ZONE'Asia/Ho_Chi_Minh',(date'2026-11-01'+d+time'17:00')AT TIME ZONE'Asia/Ho_Chi_Minh' FROM generate_series(0,24)d;
 INSERT INTO public.staff_attendance(staff_id,shift_date,status,check_in_time)VALUES(v_staff,date'2026-11-26','checked_in',timestamptz'2026-11-26 09:00+07');
 PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);SET LOCAL ROLE authenticated;
 result:=public.chot_staff_salary_month(club,2026,11);ASSERT(result->>'total_net_vnd')::bigint=5000000,result::text;
 PERFORM public.submit_staff_salary_month(club,2026,11,'L02 supplement TEST');PERFORM public.approve_staff_salary_month(club,2026,11);
 RESET ROLE;
 SELECT to_jsonb(r) INTO before_salary FROM public.staff_salary_runs r WHERE r.staff_id=v_staff;
 SET LOCAL ROLE authenticated;
 result:=public.mark_staff_salary_paid((before_salary->>'id')::uuid,'bank_transfer','TEST-BASE-5M');
 ASSERT(result->>'net_vnd')::bigint=5000000;
 before_finance:=public.get_club_finance_summary(timestamptz'2026-11-01 00:00+07',timestamptz'2026-11-30 23:59:59+07',club);
 RESET ROLE;
 SELECT to_jsonb(r) INTO before_salary FROM public.staff_salary_runs r WHERE r.staff_id=v_staff;
 SELECT snapshot INTO before_source FROM floor_private.staff_salary_sources_v1 WHERE run_id=(before_salary->>'id')::uuid;
 PERFORM set_config('request.jwt.claim.sub',employee::text,true);SET LOCAL ROLE authenticated;
 result:=public.staff_check_out(v_staff);ASSERT result->>'outcome'='checked_out',result::text;
 PERFORM set_config('request.jwt.claim.sub',accountant::text,true);
 packet:=public.get_staff_salary_adjustments_v1(club,2026,11);
 ASSERT jsonb_array_length(packet->'requests')=1,packet::text;
 ASSERT packet->'requests'->0->>'state'='pending',packet::text;
 ASSERT(packet->'requests'->0->>'amount_vnd')::bigint=200000,packet::text;
 request_id:=(packet->'requests'->0->>'id')::uuid;
 ASSERT NOT(packet->'requests'->0?'source_snapshot'),'source payload leaked in summary';
 result:=public.refresh_staff_salary_adjustment_v1((before_salary->>'id')::uuid);
 ASSERT(result->>'request_id')::uuid=request_id AND(result->>'idempotent')::boolean,result::text;
 result:=public.get_staff_salary_run_source_v1((before_salary->>'id')::uuid);
 ASSERT result->>'source_status'='verified';ASSERT result->'source'=before_source;
 PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);
 result:=public.get_club_finance_summary(timestamptz'2026-11-01 00:00+07',timestamptz'2026-11-30 23:59:59+07',club);
 ASSERT result=before_finance,'pending request changed Finance';
 RESET ROLE;
 SELECT to_jsonb(r) INTO after_salary FROM public.staff_salary_runs r WHERE r.id=(before_salary->>'id')::uuid;
 ASSERT before_salary=after_salary,'late checkout rewrote original5M receipt';
 ASSERT NOT EXISTS(SELECT 1 FROM public.staff_salary_runs WHERE adjusts_id=(before_salary->>'id')::uuid),'pending request became payable';
 ASSERT(SELECT snapshot FROM floor_private.staff_salary_sources_v1 WHERE run_id=(before_salary->>'id')::uuid)=before_source;
 PERFORM set_config('request.jwt.claim.sub',foreign_admin::text,true);SET LOCAL ROLE authenticated;
 BEGIN PERFORM public.get_staff_salary_adjustments_v1(club,2026,11);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'foreign admin read requests';denied:=false;
 BEGIN PERFORM public.get_staff_salary_run_source_v1((before_salary->>'id')::uuid);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'foreign admin read private source';
 PERFORM set_config('request.jwt.claim.sub',accountant::text,true);denied:=false;
 BEGIN PERFORM public.approve_staff_salary_adjustment_v1(request_id);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'accountant approved own supplement';
 PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);
 result:=public.approve_staff_salary_adjustment_v1(request_id);
 ASSERT result->>'status'='approved' AND(result->>'amount_vnd')::bigint=200000,result::text;
 child_id:=(result->>'run_id')::uuid;
 result:=public.approve_staff_salary_adjustment_v1(request_id);
 ASSERT(result->>'idempotent')::boolean AND(result->>'run_id')::uuid=child_id,result::text;
 result:=public.get_club_finance_summary(timestamptz'2026-11-01 00:00+07',timestamptz'2026-11-30 23:59:59+07',club);
 ASSERT(result->'cost'->>'payrollNet')::bigint=5200000,result::text;
 ASSERT(result->>'unpaidTotal')::bigint=200000,result::text;
 PERFORM set_config('request.jwt.claim.sub',foreign_admin::text,true);denied:=false;
 ASSERT NOT EXISTS(SELECT 1 FROM public.staff_salary_runs WHERE id=child_id),'foreign admin read new child';
 BEGIN PERFORM public.mark_staff_salary_paid(child_id,'cash',NULL);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'foreign admin paid child through legacy broad authority';
 PERFORM set_config('request.jwt.claim.sub',accountant::text,true);
 result:=public.mark_staff_salary_paid(child_id,'bank_transfer','TEST-SUPPLEMENT-200K');
 ASSERT(result->>'net_vnd')::bigint=200000 AND result->>'status'='paid',result::text;
 result:=public.mark_staff_salary_paid(child_id,'bank_transfer','TEST-SUPPLEMENT-200K');ASSERT(result->>'idempotent')::boolean;
 result:=public.mark_staff_salary_paid(child_id,'cash',NULL);ASSERT result->>'error'='PAYMENT_INTENT_CONFLICT';
 PERFORM set_config('request.jwt.claim.sub',foreign_admin::text,true);denied:=false;
 BEGIN PERFORM public.mark_staff_salary_paid(child_id,'bank_transfer','TEST-SUPPLEMENT-200K');EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'foreign admin recovered paid child receipt through legacy idempotent branch';denied:=false;
 BEGIN PERFORM public.get_staff_salary_report(club,2026,11);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'foreign admin read new child through legacy report';
 PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);
 result:=public.get_club_finance_summary(timestamptz'2026-11-01 00:00+07',timestamptz'2026-11-30 23:59:59+07',club);
 ASSERT(result->'cost'->>'payrollNet')::bigint=5200000 AND(result->'cost'->>'payrollGross')::bigint=5200000,result::text;
 ASSERT(result->>'unpaidTotal')::bigint=0,result::text;
 PERFORM set_config('request.jwt.claim.sub',employee::text,true);
 result:=public.get_staff_salary_run_source_v1(child_id);
 ASSERT result->>'source_status'='verified' AND(result->>'base_run_id')::uuid=(before_salary->>'id')::uuid,result::text;
 ASSERT(result->>'recorded_net_vnd')::bigint=200000 AND(result->'source'->>'net_vnd')::bigint=5200000,result::text;
 RESET ROLE;
 SELECT to_jsonb(r) INTO after_salary FROM public.staff_salary_runs r WHERE r.id=(before_salary->>'id')::uuid;
 ASSERT after_salary=before_salary,'supplement changed original5M receipt';
 ASSERT(SELECT count(*) FROM public.staff_salary_runs WHERE staff_id=v_staff)=2;
 ASSERT(SELECT sum(net_vnd) FROM public.staff_salary_runs WHERE staff_id=v_staff AND status='paid')=5200000;
 ASSERT(SELECT adjusts_id FROM public.staff_salary_runs WHERE id=child_id)=(before_salary->>'id')::uuid;
 -- Soft-delete revokes self access to new private source and child data; operators retain audit access.
 UPDATE public.staff SET deleted_at=now() WHERE id=v_staff;
 PERFORM set_config('request.jwt.claim.sub',employee::text,true);SET LOCAL ROLE authenticated;denied:=false;
 BEGIN PERFORM public.get_staff_salary_run_source_v1(child_id);EXCEPTION WHEN insufficient_privilege THEN denied:=true;END;
 ASSERT denied,'deleted employee retained private source access';
 ASSERT NOT EXISTS(SELECT 1 FROM public.staff_salary_runs WHERE id=child_id),'deleted employee retained child SELECT';
 PERFORM set_config('request.jwt.claim.sub',owner_id::text,true);
 result:=public.get_staff_salary_run_source_v1(child_id);ASSERT result->>'source_status'='verified';
 ASSERT EXISTS(SELECT 1 FROM public.staff_salary_runs WHERE id=child_id),'owner lost audit access after staff deletion';
 RESET ROLE;
END $test$;
ROLLBACK;
