import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {sql,jsonSql} from './nativeDb.mjs';
const signature='tracker_analytics_v1.safe_integer(jsonb)';
const migration=readFileSync('supabase/migrations/20261104003300_public_hud_null_proof_short_circuit.sql','utf8');
const recovery=readFileSync('tests/publicHud/null-proof.forward-rollback.sql','utf8');
const strip=s=>s.replace(/^BEGIN;\r?\n/m,'').replace(/COMMIT;\s*$/,'');
const metadata=()=>jsonSql(`SELECT to_jsonb(p)-'proisstrict' FROM pg_proc p WHERE oid='${signature}'::regprocedure;`);
const hash=()=>sql(`SELECT md5(replace(pg_get_functiondef('${signature}'::regprocedure),chr(13),''));`);
assert.equal(hash(),'c7ed2c1ef058520538fb54ef48bfc2d0');
const before=metadata();
const objectCheck=readFileSync('scripts/ops/tracker-hud-20261104-postcheck.sql','utf8').split(/\r?\n/).filter(line=>line.trimStart().startsWith("'nullProofValidatorDefinitionMatches',"));
assert.equal(objectCheck.length,1);
const checkSql=`SELECT jsonb_build_object(${objectCheck[0].trim().replace(/,$/,'')});`;
assert.equal(jsonSql(checkSql).nullProofValidatorDefinitionMatches,false);
const values=[null,'null','true','false','"123"','""','{}','[]','0','-0','1','-1','1.0','1.5','1e3','1e-3','9007199254740991','-9007199254740991','9007199254740992','-9007199254740992','1e100','-1e100'];
const matrix=`SELECT jsonb_agg(jsonb_build_object('input',v,'value',tracker_analytics_v1.safe_integer(v)) ORDER BY ord) FROM (VALUES ${values.map((v,i)=>`(${i},${v===null?'NULL':`'${v}'`}::jsonb)`).join(',')}) inputs(ord,v);`;
const expected=jsonSql(matrix);
const scope=jsonSql(`SELECT jsonb_build_object('tour',tournament_id,'player',player_id) FROM tracker_analytics_v1.hand_contributions ORDER BY hand_id LIMIT 1;`);
const histories=new Map(['anon','authenticated'].map(role=>[role,jsonSql(`SET ROLE ${role};SELECT public.get_public_player_hud_history_v1('${scope.tour}','${scope.player}');`)]));
sql(migration);
assert.equal(hash(),'a3615d0068110c9bf33939ecf8f29024');
assert.equal(jsonSql(checkSql).nullProofValidatorDefinitionMatches,true);
assert.deepEqual(metadata(),before,'STRICT must preserve function identity, body, security and ACL');
assert.deepEqual(jsonSql(matrix),expected,'Missing proof and invalid numeric evidence remain unknown');
for(const [role,history] of histories)assert.deepEqual(jsonSql(`SET ROLE ${role};SELECT public.get_public_player_hud_history_v1('${scope.tour}','${scope.player}');`),history,`${role} history must remain unchanged`);
assert.throws(()=>sql(migration,{captureFailure:true}),/preimage differs/);
assert.equal(sql(`BEGIN;${strip(recovery)}SELECT md5(replace(pg_get_functiondef('${signature}'::regprocedure),chr(13),''));ROLLBACK;`),'c7ed2c1ef058520538fb54ef48bfc2d0');
assert.equal(hash(),'a3615d0068110c9bf33939ecf8f29024');
const report={kind:'NATIVE_NULL_PROOF_VALIDATOR_NOT_HTTP_CAPACITY',passed:true,values:values.length,historyRoles:[...histories.keys()],metadataUnchangedExceptStrict:true,exactRecovery:true};
if(process.env.PUBLIC_HUD_NULL_PROOF_REPORT)writeFileSync(process.env.PUBLIC_HUD_NULL_PROOF_REPORT,JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
