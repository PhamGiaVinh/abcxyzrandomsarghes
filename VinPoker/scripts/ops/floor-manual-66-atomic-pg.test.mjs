import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {atomicSql,loadMigration,postcheckSql,preflightSql} from './floor-manual-66-release-plan.mjs';
import {receiptSql} from './floor-37-47-protected-apply.mjs';
test('PG17 atomic66 receipt failure rolls back all definitions; commit, ACL/body and replay are fenced',
  {skip:process.env.MANUAL66_PG_TEST!=='1'},()=>{
    assert.equal(process.env.PGHOST,'127.0.0.1');assert.equal(process.env.PGUSER,'postgres');
    assert.match(process.env.PGDATABASE??'',/^vinpoker_ops_floor66_atomic_/);
    assert.ok(['55464','55441'].includes(process.env.PGPORT));
    for(const k of ['PGHOSTADDR','PGSERVICE','PGSERVICEFILE','PGOPTIONS']) assert.ok(!process.env[k]);
    const query=sql=>spawnSync('psql',['-X','-qAt','-v','ON_ERROR_STOP=1'],{input:sql,encoding:'utf8'});
    const check=sql=>{const r=query(sql);assert.equal(r.status,0,r.stderr);return r.stdout.trim();};
    assert.equal(check("SELECT inet_server_addr()='127.0.0.1'::inet AND current_setting('server_version_num')::int BETWEEN 170000 AND 179999;"),'t');
    assert.equal(check("SELECT count(*)=0 FROM public.clubs;"),'t');
    assert.equal(check("SELECT to_regclass('supabase_migrations.schema_migrations') IS NULL;"),'t');
    check('CREATE SCHEMA supabase_migrations;CREATE TABLE supabase_migrations.schema_migrations(version text PRIMARY KEY,name text,statements text[]);');
    // Read-only gate is executable on a pristine retained schema, not just text.
    const pre=JSON.parse(check(preflightSql().replace("'database',current_database()","'database','postgres'")));
    assert.equal(pre.existing,0);assert.equal(pre.namespace_absent,true);
    check(`CREATE FUNCTION public.reject66_receipt() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'injected66_receipt_failure';END $$;
      CREATE TRIGGER reject66 BEFORE INSERT ON supabase_migrations.schema_migrations FOR EACH ROW EXECUTE FUNCTION public.reject66_receipt();`);
    const failed=query(atomicSql());assert.notEqual(failed.status,0);assert.match(failed.stderr,/injected66_receipt_failure/);
    assert.equal(check("SELECT to_regprocedure('public.floor_add_manual_player_v1(uuid,text,uuid,integer,uuid,bigint,bigint,uuid,uuid)') IS NULL;"),'t');
    assert.equal(check("SELECT md5(replace(prosrc,chr(13),'')) FROM pg_proc WHERE oid='public.floor_assign_entry_to_seat(uuid,uuid,integer,bigint,uuid)'::regprocedure;"),'d7aa29ca2c6b01f3aa3d03b28ce6930b');
    assert.deepEqual(JSON.parse(check(receiptSql(loadMigration()))),{count:0,exact:false});
    check('DROP TRIGGER reject66 ON supabase_migrations.schema_migrations;DROP FUNCTION public.reject66_receipt();');
    const corrupted=query(atomicSql().replace("'error','ACTOR_CHANGED'","'error','BROKEN_ACTOR_CHANGED'"));
    assert.notEqual(corrupted.status,0);assert.match(corrupted.stderr,/manual66_object_postcheck_failed/);
    assert.equal(check("SELECT to_regprocedure('public.floor_add_manual_player_v1(uuid,text,uuid,integer,uuid,bigint,bigint,uuid,uuid)') IS NULL;"),'t');
    assert.deepEqual(JSON.parse(check(receiptSql(loadMigration()))),{count:0,exact:false});
    check(atomicSql());check(postcheckSql());
    assert.deepEqual(JSON.parse(check(receiptSql(loadMigration()))),{count:1,exact:true});
    const signature='public.get_floor_manual_player_receipt_v1(uuid,uuid,uuid)';
    check(`ALTER FUNCTION ${signature} SET search_path=public;`);
    assert.notEqual(query(postcheckSql()).status,0);
    check(`ALTER FUNCTION ${signature} SET search_path='';`);check(postcheckSql());
    check(`GRANT EXECUTE ON FUNCTION ${signature} TO anon;`);assert.notEqual(query(postcheckSql()).status,0);
    check(`REVOKE EXECUTE ON FUNCTION ${signature} FROM anon;`);check(postcheckSql());
    const replay=query(atomicSql());assert.notEqual(replay.status,0);assert.match(replay.stderr,/manual66_precondition_drift/);
    console.log('MANUAL66_ATOMIC_ROLLBACK_COMMIT_ACL_REPLAY_PASS');
  });
